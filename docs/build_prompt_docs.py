def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def write_html(doc, path):
    e = html.escape
    blocks = all_blocks(doc)
    # anchors for every heading <= 2 that lacks one
    used = set()
    hs = []
    for b in blocks:
        if b[0] == "h":
            a = b[3] or slug(b[2])
            base, n = a, 2
            while a in used:
                a = "%s-%d" % (base, n)
                n += 1
            used.add(a)
            hs.append((b[1], b[2], a))
    it = iter(hs)
    o = ["<!doctype html>", '<html lang="en"><head><meta charset="utf-8">',
         '<meta name="viewport" content="width=device-width, initial-scale=1">',
         "<title>KSSL Prompt Book</title>", "<style>%s</style>" % CSS, "</head><body>",
         '<div class="bar"><a href="#contents">KSSL Prompt Book - contents</a></div>', "<main>",
         '<h1 class="title">KSSL Prompt Book</h1>',
         "<p>Generated %s</p>" % e(GENERATED), '<p class="note">%s</p>' % e(SOURCE_NOTE),
         '<nav class="toc" id="contents"><details open><summary>Contents</summary><ul>']
    for lvl, text, a in hs:
        if lvl <= 2:
            o.append('<li class="l%d"><a href="#%s">%s</a></li>' % (lvl, e(a), e(text)))
    o.append("</ul></details></nav>")
    for b in blocks:
        k = b[0]
        if k == "h":
            lvl, text, a = next(it)
            o.append('<h%d id="%s">%s</h%d>' % (lvl, e(a), e(text), lvl))
        elif k == "p":
            o.append("<p>%s</p>" % e(b[1]))
        elif k == "ul":
            o.append("<ul>%s</ul>" % "".join("<li>%s</li>" % e(x) for x in b[1]))
        elif k == "table":
            o.append('<div class="tw"><table><thead><tr>%s</tr></thead><tbody>%s</tbody></table></div>' % (
                "".join("<th>%s</th>" % e(h) for h in b[1]),
                "".join("<tr>%s</tr>" % "".join("<td>%s</td>" % e(str(c)) for c in r) for r in b[2])))
        elif k == "code":
            o.append("<pre><code>%s</code></pre>" % e(clean(b[1])))
    o.append("</main></body></html>")
    Path(path).write_text("\n".join(o), encoding="utf8")


# ---- markdown (one set)
def md_escape_cell(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def write_md(doc, set_key, sets, path):
    info = sets[set_key]
    ids = [pid for pid in info.get("prompts", []) if pid in doc["per"]]
    o = ["# KSSL prompts: %s" % info.get("title", set_key), "", "_%s_" % SOURCE_NOTE, "",
         "Set: %s  " % info.get("title", set_key),
         "Prompts in run order: %s  " % ", ".join(ids),
         "When: %s  " % info.get("when", ""),
         "Needs: %s" % info.get("needs", ""), "",
         "Each prompt is filled from the staging database at run time, the model replies with one JSON "
         "envelope, the loader writes the staging tables and a human approves in the review site. "
         "The shared system prompt and allowed values are in docs/KSSL_Prompts.docx / .html.", ""]
    for pid in ids:
        for b in doc["per"][pid]:
            k = b[0]
            if k == "h":
                o += ["", "#" * b[1] + " " + b[2], ""]
            elif k == "p":
                o += [b[1], ""]
            elif k == "ul":
                o += ["- " + x for x in b[1]] + [""]
            elif k == "table":
                o.append("| " + " | ".join(md_escape_cell(h) for h in b[1]) + " |")
                o.append("|" + "---|" * len(b[1]))
                for r in b[2]:
                    o.append("| " + " | ".join(md_escape_cell(c) for c in r) + " |")
                o.append("")
            elif k == "code":
                text = clean(b[1])
                runs = [len(m) for m in re.findall(r"`+", text)]
                fence = "`" * max(3, (max(runs) + 1) if runs else 3)
                o += [fence, text, fence, ""]
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text("\n".join(o).rstrip() + "\n", encoding="utf8")


