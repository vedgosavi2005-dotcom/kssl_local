def clean(s):
    """Strip control characters that XML cannot hold; tabs -> spaces."""
    s = str(s).replace("\t", "    ")
    return re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f]", "", s)


# ---------------------------------------------------------------- load sources
def load_yaml(p):
    with open(p, encoding="utf8") as f:
        return yaml.safe_load(f)


def load_all():
    shared = load_yaml(PROMPTS / "_shared.yml")
    sets = load_yaml(PROMPTS / "sets.yml")
    prompts = {}
    for f in sorted(PROMPTS.glob("*.yml")):
        if f.name in ("_shared.yml", "sets.yml"):
            continue
        d = load_yaml(f)
        prompts[d["id"]] = d
    return shared, sets, prompts


def allowed_values_table():
    """Rows of the 'Allowed values' table in FORMAT.md as (columns, values)."""
    text = (PROMPTS / "FORMAT.md").read_text(encoding="utf8")
    m = re.search(r"^##\s+Allowed values.*?$(.*?)(?=^##\s|\Z)", text, re.S | re.M)
    rows = []
    if not m:
        return rows
    for line in m.group(1).splitlines():
        line = line.strip()
        if not line.startswith("|"):
            continue
        cells = [c.strip().replace("`", "") for c in line.strip("|").split("|")]
        if len(cells) < 2 or set(cells[0]) <= set("-: ") or cells[0].lower() == "column(s)":
            continue
        rows.append((cells[0], " | ".join(cells[1:])))
    return rows


def last_runs(ids):
    """Latest loaded run per prompt from the local staging DB (read-only); {} if unreachable."""
    out = {}
    try:
        import psycopg2
        conn = psycopg2.connect(os.environ.get("KSSL_STAGING_DSN", DEFAULT_DSN), connect_timeout=3)
        conn.set_session(readonly=True, autocommit=True)
        cur = conn.cursor()
        for pid in ids:
            cur.execute("SELECT status, seconds, tokens_in, tokens_out, cost_usd, started_at "
                        "FROM staging.prompt_run WHERE prompt_id = %s AND status = 'loaded' "
                        "ORDER BY started_at DESC LIMIT 1", (pid,))
            r = cur.fetchone()
            if r:
                out[pid] = r
        conn.close()
    except Exception:
        return {}
    return out


def fmt_run(r):
    status, secs, tin, tout, cost, started = r
    parts = [str(status)]
    if secs is not None:
        parts.append("%.1f s" % float(secs))
    if tin is not None or tout is not None:
        parts.append("%s tokens in / %s out" % (format(tin, ",") if tin is not None else "?",
                                              format(tout, ",") if tout is not None else "?"))
    if cost is not None:
        parts.append("$%.4f" % float(cost))
    if started is not None:
        parts.append(started.strftime("%Y-%m-%d %H:%M") if hasattr(started, "strftime") else str(started))
    return ", ".join(parts)


# ---------------------------------------------------------------- output spec -> readable rows
def listify(v):
    if v is None:
        return []
    return list(v) if isinstance(v, (list, tuple)) else [v]


def column_rules(spec):
    """Return ordered {column: [rule strings]} from the many shapes `columns` + sibling keys take."""
    cols = {}
    raw = spec.get("columns")
    if isinstance(raw, dict):
        for c, r in raw.items():
            cols[c] = dict(r) if isinstance(r, dict) else {}
    else:
        for c in listify(raw):
            cols[c] = {}
    # table-level sibling keys (children style)
    for c in listify(spec.get("required")) if not isinstance(spec.get("required"), dict) else []:
        cols.setdefault(c, {})["required"] = True
    for c in listify(spec.get("judgement")) if not isinstance(spec.get("judgement"), dict) else []:
        cols.setdefault(c, {})["judgement"] = True
    for key in ("enum", "enum_from", "max", "from_ref", "type"):
        v = spec.get(key)
        if isinstance(v, dict):
            for c, val in v.items():
                cols.setdefault(c, {})[key] = val
    rules = {}
    for c, r in cols.items():
        out = []
        if r.get("required"):
            out.append("required")
        if "type" in r:
            out.append("type: %s" % r["type"])
        if "max" in r:
            out.append("max %s characters" % r["max"])
        if "enum" in r:
            out.append("one of: " + " | ".join(str(x) for x in listify(r["enum"])))
        if "enum_from" in r:
            out.append("one of the values listed in %s" % r["enum_from"])
        if r.get("judgement"):
            out.append("judgement (needs a reason)")
        if "from_ref" in r:
            out.append("a name; the loader resolves it via %s" % r["from_ref"])
        for k, v in r.items():
            if k not in ("required", "type", "max", "enum", "enum_from", "judgement", "from_ref"):
                out.append("%s: %s" % (k, v))
        rules[c] = out
    return rules


def loader_hint(v):
    if isinstance(v, dict):
        return "picked by the value found in the row: " + "; ".join("%s -> %s" % (k, w) for k, w in v.items())
    s = str(v)
    if s.startswith("new_id_or_ref_"):
        return "generated id, or the id of the referenced row (which is then extended)"
    if s in ("new_id", "new_id_if_missing"):
        return "stable generated id (same inputs, same id)"
    if s == "parent_id":
        return "key of the parent row"
    if s in ("index", "index_plus_1_of_output_order"):
        return "1-based position in the output order"
    if s in ("run_date", "run_time", "now"):
        return "date/time of the run"
    if s == "keep":
        return "left as stored"
    if s.startswith("subject."):
        return "taken from the subject row"
    if s.startswith("derive."):
        return "set by the derive step %s" % s[7:]
    if s.startswith("copy_of_") or s.startswith("copy_from_"):
        return "copied from another column / related row"
    if s.startswith("constant_"):
        return "fixed value '%s'" % s[9:]
    if s.startswith("transient."):
        return "from a model field that is checked but not stored"
    if s.startswith("resolved_"):
        return "from the reference row the loader matched"
    if s.startswith("rank_by_"):
        return "rank computed from the column named"
    if s.startswith("from_ui."):
        return "value read from the UI lookup table"
    if s.startswith("count_") or s.startswith("join_"):
        return "roll-up over the rows written"
    return ""


def flatten_output(name, spec, path=()):
    """Yield (path, spec) for a table and its children, depth first."""
    yield path + (name,), spec
    if isinstance(spec, dict):
        for cn, cs in (spec.get("children") or {}).items():
            yield from flatten_output(cn, cs if isinstance(cs, dict) else {}, path + (name,))


def output_blocks(p):
    out = p.get("output") or {}
    blocks = []
    if p.get("handler"):
        blocks.append(("p", "The answer is applied by the code module prompts/%s.py rather than the generic loader, "
                            "so the rules below are documentary." % p["handler"]))
    for tname, tspec in out.items():
        for path, spec in flatten_output(tname, tspec or {}):
            blocks.append(("h", 4, "Table: " + " > ".join(path), None))
            flags = []
            if spec.get("card"):
                flags.append("one review card per record")
            if spec.get("loader_only"):
                flags.append("built by the loader only; the model must not write it")
            if spec.get("update_only"):
                flags.append("updates existing rows only (nothing inserted or deleted)")
            if spec.get("replace"):
                flags.append("when the run loads anything, all previous rows are replaced (%s)" % spec["replace"])
            if flags:
                blocks.append(("p", "Behaviour: " + "; ".join(flags) + "."))
            if spec.get("key"):
                blocks.append(("p", "Id key (a re-run with the same key updates the same row): " +
                               ", ".join(str(k) for k in listify(spec["key"])) + "."))
            rules = column_rules(spec)
            if rules:
                blocks.append(("table", ["Column", "Rule"],
                               [[c, "; ".join(r) if r else "free text, optional"] for c, r in rules.items()]))
            if spec.get("refs"):
                blocks.append(("p", "References the record may carry (the model writes a name, the loader finds the row):"))
                blocks.append(("table", ["Reference", "Resolves to"], [[k, str(v)] for k, v in spec["refs"].items()]))
            if spec.get("transient"):
                rows = []
                for k, r in spec["transient"].items():
                    rr = []
                    r = r if isinstance(r, dict) else {}
                    if r.get("required"):
                        rr.append("required")
                    if "enum" in r:
                        rr.append("one of: " + " | ".join(str(x) for x in listify(r["enum"])))
                    if r.get("judgement"):
                        rr.append("judgement (needs a reason)")
                    if "from_ref" in r:
                        rr.append("a name; resolved via %s" % r["from_ref"])
                    rows.append([k, "; ".join(rr) if rr else "free text, optional"])
                blocks.append(("p", "Fields the model gives that are checked but not stored as columns:"))
                blocks.append(("table", ["Field", "Rule"], rows))
            if spec.get("loader") and isinstance(spec["loader"], dict):
                blocks.append(("p", "Columns filled by the loader (not by the model):"))
                blocks.append(("table", ["Column", "Filled with", "Meaning"],
                               [[c, str(v), loader_hint(v)] for c, v in spec["loader"].items()]))
            if spec.get("rows"):
                blocks.append(("p", "Fixed rows the loader writes, in order:"))
                keys = []
                for r in spec["rows"]:
                    for k in r:
                        if k not in keys:
                            keys.append(k)
                blocks.append(("table", keys, [[str(r.get(k, "")) for k in keys] for r in spec["rows"]]))
            if spec.get("creates"):
                items = []
                for tbl, cs in spec["creates"].items():
                    ld = (cs or {}).get("loader") or {}
                    items.append("%s: found or created if missing; fills %s" %
                                 (tbl, ", ".join("%s = %s" % (k, v) for k, v in ld.items())))
                blocks.append(("p", "The loader may also find or create rows:"))
                blocks.append(("ul", items))
    return blocks


# ---------------------------------------------------------------- document model
def build_prompt_blocks(pid, p, shared, sets, set_of, last):
    sname = set_of.get(pid)
    sinfo = sets.get(sname, {}) if sname else {}
    order = (sinfo.get("prompts") or []).index(pid) + 1 if sname else None
    web = p.get("web_search", shared.get("web_search", False))
    cadence = str(p.get("cadence", ""))
    if p.get("recurring") is False:
        cadence += " (a decided subject is never run again at the same version)"
    elif p.get("recurring") is True:
        cadence += " (re-runs every period)"
    b = [("h", 2, "%s: %s" % (pid, p.get("title", "")), "p-" + pid)]
    meta = [
        ["Version", str(p.get("version", ""))],
        ["Set", "%s (run position %s of %s)" % (sinfo.get("title", sname), order, len(sinfo.get("prompts", [])))
         if sname else "not in any set"],
        ["Cadence", cadence],
        ["Model", str(p.get("model", shared.get("model", "")))
         + ("" if p.get("model") else " (default from _shared.yml)")],
        ["Web search", "yes" if web else "no"],
        ["Fills (tables)", ", ".join(p.get("fills", []))],
        ["Shows on", str(p.get("shows_on", ""))],
    ]
    if p.get("handler"):
        meta.append(["Handler", "prompts/%s.py (handler prompt: the code applies the answer)" % p["handler"]])
    if p.get("derive"):
        meta.append(["Derive steps", ", ".join(p["derive"])])
    b.append(("table", ["Item", "Value"], meta))

    subj = p.get("subject", {})
    b.append(("h", 3, "Subject", None))
    hint = SUBJECT_HINT.get(pid, "one row returned by the subject query.")
    b.append(("p", "Key column: %s. One subject is %s Each subject is one run of the prompt; "
                   "the key makes a run unique." % (subj.get("key"), hint)))
    b.append(("code", (subj.get("query") or "").rstrip()))

    docs = subj.get("documents") or []
    b.append(("h", 3, "Documents", None))
    if not docs:
        b.append(("p", "None."))
    for i, d in enumerate(docs, 1):
        if d.get("from") == "url":
            b.append(("p", "Document %d: from a url field. The runner fetches the page text of column '%s' "
                           "of the subject row (skipped if empty)." % (i, d.get("field"))))
        elif d.get("from") == "sql":
            b.append(("p", "Document %d: from SQL. The rows are given to the model as text. Subject "
                           "placeholders in the query are bound parameters." % i))
            b.append(("code", (d.get("query") or "").rstrip()))
        else:
            b.append(("p", "Document %d: %s" % (i, d)))

    b.append(("h", 3, "Context blocks", None))
    ctxs = p.get("context") or []
    blk = shared.get("context_blocks", {})
    b.append(("table", ["Block", "What it holds"], [[c, blk.get(c, "")] for c in ctxs]) if ctxs else ("p", "None."))

    b.append(("h", 3, "Task text (verbatim)", None))
    b.append(("code", (p.get("task") or "").rstrip()))

    b.append(("h", 3, "Output rules", None))
    b.extend(output_blocks(p))

    if p.get("derive"):
        b.append(("h", 3, "Derive steps", None))
        b.append(("p", "Named code steps that run after the rows are written (prompts/derive.py): " +
                       ", ".join(p["derive"]) + "."))
    if pid in last:
        b.append(("h", 3, "Last test run", None))
        b.append(("p", "Status "  + fmt_run(last[pid]) + "."))
    return b


def build_doc(shared, sets, prompts):
    set_of = {pid: s for s, info in sets.items() for pid in info.get("prompts", [])}
    ordered = [pid for s in sets for pid in sets[s].get("prompts", []) if pid in prompts]
    ordered += [pid for pid in prompts if pid not in ordered]
    last = last_runs(ordered)

    n = len(prompts)
    nsets = len(sets)
    head = []
    head.append(("h", 1, "1. Summary", "summary"))
    head.append(("p", "This book describes the %d prompts that fill the KSSL staging database. Each prompt is "
                      "filled at run time from the staging database ({{client.*}} values, context blocks, one "
                      "subject row and its documents), so nothing about the client is typed into a prompt. The "
                      "model replies with one JSON envelope; a loader writes it into the staging tables and "
                      "records its sources; a human approves each card in the review site before anything goes "
                      "live. Nothing is invented: every fact needs a source quote and every judgement needs a "
                      "one-sentence reason." % n))
    head.append(("h", 1, "2. How a prompt works", "how"))
    head.append(("ul", [
        "Subject: a query on the staging database returns the rows to work on. One run per row (for example "
        "one competitor, one news article or one tender). The key column makes the run unique, so a re-run "
        "of the same subject updates its cards instead of duplicating them.",
        "Context blocks: lists filled from the database (the client, its products, the competitors, the "
        "technology categories ...). They are the only names the model may use when it refers to a record.",
        "Documents: the source text given to the model: the text of a web page, or rows from the database "
        "turned into text. Facts must come from these first; web search is used only by prompts that "
        "switch it on.",
        "Task: the instruction text, with {{placeholders}} filled in before the call. Allowed values are "
        "listed inside the task.",
        "Output rules: which tables and columns the model may fill and how (required, maximum length, "
        "allowed values, judgement, reference by name). Anything else is rejected.",
        "Loader: the code that writes the answer to the staging tables. It fills the bookkeeping columns "
        "(ids, order, dates) and resolves names to ids. A name it cannot find is not invented: the row is "
        "dropped and logged.",
        "Derive: optional named code steps that run after loading and compute scores or roll-ups.",
        "Review: every card waits in the review site for Approve before it goes live.",
    ]))
    head.append(("h", 1, "3. The run sets", "sets"))
    rows = []
    for s, info in sets.items():
        rows.append([info.get("title", s), " > ".join(info.get("prompts", [])),
                     str(info.get("when", "")), str(info.get("needs", ""))])
    head.append(("table", ["Set", "Prompts in run order", "When", "Needs"], rows))
    handlers = [pid for pid in ordered if prompts[pid].get("handler")]
    if handlers:
        head.append(("p", "Note: " + ", ".join("%s.yml" % h for h in handlers) +
                          " is a handler prompt (%s): the model only groups the headlines into stories and "
                          "gives each a category; the code in prompts/%s.py writes the result." %
                          (", ".join(prompts[h]["handler"] for h in handlers), prompts[handlers[0]]["handler"])))
    head.append(("p", "Within a set the order matters: a later prompt reads what an earlier one wrote."))

    body = [("h", 1, "4. The prompts", "prompts")]
    per = {}
    for pid in ordered:
        blocks = build_prompt_blocks(pid, prompts[pid], shared, sets, set_of, last)
        per[pid] = blocks
        body.append(("pb",))
        body.extend(blocks)

    app = [("pb",)]
    app.append(("h", 1, "Appendix A. Shared system prompt and JSON envelope", "appA"))
    app.append(("p", "Sent with every prompt (prompts/_shared.yml). Default model: %s; default web search: %s." %
                (shared.get("model"), "yes" if shared.get("web_search") else "no")))
    app.append(("code", (shared.get("system") or "").rstrip()))
    app.append(("h", 1, "Appendix B. Allowed values", "appB"))
    app.append(("p", "From prompts/FORMAT.md, \"Allowed values\": the pages expect exactly these values."))
    app.append(("table", ["Column(s)", "Values"], [list(r) for r in allowed_values_table()]))
    if "news" in prompts:
        cats = []
        try:
            cats = prompts["news"]["output"]["news_story"]["columns"]["category"]["enum"]
        except Exception:
            pass
        if cats:
            app.append(("h", 2, "News categories (prompt news)", None))
            app.append(("ul", [str(c) for c in cats]))
    app.append(("h", 1, "Appendix C. Context blocks", "appC"))
    app.append(("p", "Rendered from the staging database at run time; an empty list shows as \"none on record\"."))
    app.append(("table", ["Block", "What it holds"], [[k, v] for k, v in shared.get("context_blocks", {}).items()]))

    return {"summary": head, "body": body, "app": app, "per": per, "ordered": ordered, "set_of": set_of}


# ---------------------------------------------------------------- renderers
def toc_entries(blocks):
    return [(b[1], b[2], b[3]) for b in blocks if b[0] == "h" and b[1] <= 2]


def all_blocks(doc):
    return doc["summary"] + doc["body"] + doc["app"]


# ---- docx
def write_docx(doc, path):
    from docx import Document
    from docx.enum.style import WD_STYLE_TYPE
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Cm, Pt

    d = Document()
    sec = d.sections[0]
    sec.left_margin = sec.right_margin = Cm(2)
    sec.top_margin = sec.bottom_margin = Cm(2)
    d.styles["Normal"].font.name = "Calibri"
    d.styles["Normal"].font.size = Pt(10.5)

    code = d.styles.add_style("CodeBlock", WD_STYLE_TYPE.PARAGRAPH)
    code.base_style = d.styles["Normal"]
    code.font.name = "Consolas"
    code.font.size = Pt(9)
    code.element.rPr.rFonts.set(qn("w:eastAsia"), "Consolas")
    code.element.rPr.rFonts.set(qn("w:cs"), "Consolas")
    code.paragraph_format.space_after = Pt(0)
    code.paragraph_format.space_before = Pt(0)
    code.paragraph_format.left_indent = Cm(0.2)
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), "F2F2F2")
    code.element.get_or_add_pPr().append(shd)

    def add_field(par, instr):
        for t, txt in (("begin", None), (None, instr), ("end", None)):
            r = par.add_run()
            if t:
                fc = OxmlElement("w:fldChar")
                fc.set(qn("w:fldCharType"), t)
                r._r.append(fc)
            else:
                it = OxmlElement("w:instrText")
                it.set(qn("xml:space"), "preserve")
                it.text = txt
                r._r.append(it)

    fp = sec.footer.paragraphs[0]
    fp.text = "KSSL Prompt Book - generated %s - page " % GENERATED
    add_field(fp, "PAGE")

    d.add_paragraph("KSSL Prompt Book", style="Title")
    d.add_paragraph("Generated " + GENERATED)
    p = d.add_paragraph(SOURCE_NOTE)
    p.runs[0].italic = True

    # manual contents list (a TOC field would need a manual refresh on open)
    d.add_heading("Contents", level=1)
    for lvl, text, _ in toc_entries(all_blocks(doc)):
        cp = d.add_paragraph(clean(text))
        cp.paragraph_format.left_indent = Cm(0 if lvl == 1 else 0.8)
        cp.paragraph_format.space_after = Pt(0)
    d.add_page_break()

    def table(header, rows):
        t = d.add_table(rows=1, cols=len(header))
        try:
            t.style = d.styles["Light Grid Accent 1"]
        except KeyError:
            t.style = d.styles["Table Grid"]
        for i, h in enumerate(header):
            c = t.rows[0].cells[i]
            c.text = clean(h)
        for r in rows:
            cells = t.add_row().cells
            for i in range(len(header)):
                cells[i].text = clean(r[i] if i < len(r) else "")
        for row in t.rows:
            for c in row.cells:
                for par in c.paragraphs:
                    par.paragraph_format.space_after = Pt(0)
                    for run in par.runs:
                        run.font.size = Pt(9)
        trPr = t.rows[0]._tr.get_or_add_trPr()
        th = OxmlElement("w:tblHeader")
        th.set(qn("w:val"), "true")
        trPr.append(th)
        d.add_paragraph()

    for b in all_blocks(doc):
        k = b[0]
        if k == "h":
            d.add_heading(clean(b[2]), level=b[1])
        elif k == "p":
            d.add_paragraph(clean(b[1]))
        elif k == "ul":
            for it in b[1]:
                d.add_paragraph(clean(it), style="List Bullet")
        elif k == "table":
            table(b[1], b[2])
        elif k == "code":
            lines = clean(b[1]).split("\n") if b[1] else [""]
            for ln in lines:
                d.add_paragraph(ln, style="CodeBlock")
            d.add_paragraph()
        elif k == "pb":
            d.add_page_break()
    d.save(str(path))


