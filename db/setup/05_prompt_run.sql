-- staging.prompt_run: one row per prompt run (python -m prompts.run). See prompts/FORMAT.md.
-- Applied to kssl_staging by db/make_databases.sh. Safe to re-run.
CREATE TABLE IF NOT EXISTS staging.prompt_run (
    run_id         uuid          NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
    prompt_id      text          NOT NULL,
    prompt_version text,
    subject_key    text,
    model          text,
    web_search     boolean,
    started_at     timestamptz   NOT NULL DEFAULT now(),
    seconds        numeric(8,1),
    tokens_in      integer,
    tokens_out     integer,
    cost_usd       numeric(10,4),
    status         text          NOT NULL CHECK (status IN ('loaded', 'skipped', 'rejected', 'failed', 'dry_run')),
    skip_reason    text,
    error          text,
    unresolved     jsonb,                 -- names the loader could not resolve (rows dropped)
    rows_loaded    integer,
    loaded         jsonb,                 -- [{table, id}] cards written (the next run of this subject replaces them)
    details        jsonb,                 -- warnings, rejected rows, not_found, conflicts, fetched urls
    prompt_text    text,
    raw_output     text
);
CREATE INDEX IF NOT EXISTS prompt_run_prompt_subject ON staging.prompt_run (prompt_id, subject_key, started_at DESC);

