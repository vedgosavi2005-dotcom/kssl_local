-- Tables and columns the ported 137Parallax UI needs (docs/ui_port/MAPPING.md section C).
-- Applied by db/make_databases.sh to BOTH databases (like 08): the DO blocks create each table in whichever of these schemas exists in the
-- database they run in:  staging + staging_ui (kssl_staging)   |   serving + ui (kssl_serving).
--   C1 ui tables       staging_ui.X / ui.X       section_visibility, partner_category, partner_overlap_kind, partner_overlap_effect, filter_option
--   C2 content tables  staging.X / serving.X     competitive_synthesis, competitive_synthesis_vulnerability, competitive_synthesis_vulnerability_trace,
--                                                competitive_field_synthesis, market_award, market_segment_assessment, patent_field_assessment
--   C3 added columns   client_verdict, client_impact, description, threat_level, client_relevance, area_label, metric_key
-- No foreign keys: no table of this schema has a primary key to point at (kssl_schema_from_docx.sql declares none) and Approve writes a table at a time,
-- so a link (competitor_id, vulnerability_id, relationship_id, overlap_kind) is a plain column that equals the parent's key, as everywhere else.
-- The only_via_approve guard trigger is attached to every new serving.* / ui.* table at the end (same statement as db/setup/04_serving_db.sql).
-- Idempotent: create table if not exists, add column if not exists, triggers replaced. Never drops data.
DO $$
DECLARE s text;
BEGIN
    -- C1: ui tables
    FOREACH s IN ARRAY ARRAY['staging_ui', 'ui'] LOOP
        IF to_regnamespace(s) IS NULL THEN CONTINUE; END IF;
        EXECUTE format('CREATE TABLE IF NOT EXISTS %I.section_visibility (
            section_key text PRIMARY KEY,
            visible     boolean NOT NULL,
            note        text)', s);
        EXECUTE format('CREATE TABLE IF NOT EXISTS %I.partner_category (
            category_key   text PRIMARY KEY,
            group_key      text NOT NULL,
            group_label    text NOT NULL,
            category_label text NOT NULL,
            short_label    text,
            definition     text,
            overlap_kind   text,
            display_order  integer NOT NULL)', s);
        EXECUTE format('CREATE TABLE IF NOT EXISTS %I.partner_overlap_kind (
            overlap_kind  text PRIMARY KEY,
            kind_label    text NOT NULL,
            lead          text,
            display_order integer NOT NULL)', s);
        EXECUTE format('CREATE TABLE IF NOT EXISTS %I.partner_overlap_effect (
            effect_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            overlap_kind  text NOT NULL,
            display_order integer NOT NULL,
            effect_title  text NOT NULL,
            effect_text   text NOT NULL)', s);
        -- the filter pills and card badge words of the three overview feeds, and the stance words: one row per option.
        -- A stance is threat or watch and nothing else; a group with no rows draws no pills.
        EXECUTE format('CREATE TABLE IF NOT EXISTS %I.filter_option (
            filter_group  text NOT NULL,
            option_code   text NOT NULL,
            option_label  text NOT NULL,
            badge_label   text,
            display_order integer NOT NULL,
            PRIMARY KEY (filter_group, option_code))', s);
        -- C3: the one ui column
        IF to_regclass(s || '.competitive_metric') IS NOT NULL THEN
            EXECUTE format('ALTER TABLE %I.competitive_metric ADD COLUMN IF NOT EXISTS metric_key text', s);
        END IF;
    END LOOP;

    -- C2: content tables
    FOREACH s IN ARRAY ARRAY['staging', 'serving'] LOOP
        IF to_regnamespace(s) IS NULL THEN CONTINUE; END IF;
        EXECUTE format('CREATE TABLE IF NOT EXISTS %I.competitive_synthesis (
            competitor_id   uuid PRIMARY KEY,
            thesis          text,
            strategy_thesis text,
            strategy_pattern text,
            strategy_sowhat text,
            source_url      text,
            source_tier     text)', s);
        EXECUTE format('CREATE TABLE IF NOT EXISTS %I.competitive_synthesis_vulnerability (
            vulnerability_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
            competitor_id    uuid NOT NULL,
            display_order    integer NOT NULL,
            title            text NOT NULL,
            intel            text,
            from_labels      text,
            source_url       text,
            source_tier      text)', s);
        EXECUTE format('CREATE TABLE IF NOT EXISTS %I.competitive_synthesis_vulnerability_trace (
            trace_id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
            vulnerability_id uuid NOT NULL,
            relationship_id  uuid NOT NULL,
            source_url       text,
            source_tier      text)', s);
        EXECUTE format('CREATE TABLE IF NOT EXISTS %I.competitive_field_synthesis (
            synthesis_id  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
            row_kind      text NOT NULL CHECK (row_kind IN (''pattern'', ''bottom_line'')),
            display_order integer NOT NULL,
            field_title   text,
            pattern       text,
            implication   text,
            support_count integer,
            support_total integer,
            bottom_line   text,
            source_url    text,
            source_tier   text)', s);
        EXECUTE format('CREATE TABLE IF NOT EXISTS %I.market_award (
            award_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            segment        text,
            winner         text,
            brand          text,
            buyer          text,
            site           text,
            country_name   text,
            programme      text,
            title          text,
            title_local    text,
            tender_number  text,
            award_date     date,
            award_year     integer,
            value_amount   numeric,
            value_currency text,
            value_text     text,
            bids           integer,
            source_url     text,
            source_tier    text)', s);
        EXECUTE format('CREATE TABLE IF NOT EXISTS %I.market_segment_assessment (
            segment        text PRIMARY KEY,
            recommendation text,
            source_url     text,
            source_tier    text)', s);
        EXECUTE format('CREATE TABLE IF NOT EXISTS %I.patent_field_assessment (
            area_label           text PRIMARY KEY,
            crowding             text,
            client_position_note text,
            source_url           text,
            source_tier          text)', s);

        -- C3: columns added to existing tables
        IF to_regclass(s || '.competitive_partnership') IS NOT NULL THEN
            EXECUTE format('ALTER TABLE %I.competitive_partnership
                ADD COLUMN IF NOT EXISTS client_verdict text,
                ADD COLUMN IF NOT EXISTS client_impact text', s);
        END IF;
        IF to_regclass(s || '.competitive_news_article') IS NOT NULL THEN
            EXECUTE format('ALTER TABLE %I.competitive_news_article ADD COLUMN IF NOT EXISTS description text', s);
        END IF;
        IF to_regclass(s || '.competitive_patent_filing') IS NOT NULL THEN
            EXECUTE format('ALTER TABLE %I.competitive_patent_filing
                ADD COLUMN IF NOT EXISTS threat_level text,
                ADD COLUMN IF NOT EXISTS client_relevance text,
                ADD COLUMN IF NOT EXISTS area_label text', s);
        END IF;
    END LOOP;
END $$;

-- Guard trigger on the live copies only (serving DB): writes allowed only inside Approve / Unpublish (kssl.approve = 'on').
-- The function is created by db/setup/04_serving_db.sql, which make_databases.sh applies before this file.
DO $$
DECLARE r record;
BEGIN
    IF to_regprocedure('public.kssl_only_via_approve()') IS NULL THEN RETURN; END IF;
    FOR r IN SELECT schemaname, tablename FROM pg_tables
             WHERE (schemaname = 'ui' AND tablename IN ('section_visibility', 'partner_category', 'partner_overlap_kind', 'partner_overlap_effect', 'filter_option'))
                OR (schemaname = 'serving' AND tablename IN ('competitive_synthesis', 'competitive_synthesis_vulnerability',
                    'competitive_synthesis_vulnerability_trace', 'competitive_field_synthesis', 'market_award',
                    'market_segment_assessment', 'patent_field_assessment')) LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS only_via_approve ON %I.%I', r.schemaname, r.tablename);
        EXECUTE format('CREATE TRIGGER only_via_approve BEFORE INSERT OR UPDATE OR DELETE ON %I.%I
                        FOR EACH STATEMENT EXECUTE FUNCTION public.kssl_only_via_approve()',
                       r.schemaname, r.tablename);
    END LOOP;
END $$;
